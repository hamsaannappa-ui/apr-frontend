// Arithmatic Operators

let val = 7 + 5; // Addition

console.log(val);

val = 7 / 5; // Division

console.log(val);

val = 7 * 5; // Multiplication

console.log(val);

val = 7 - 5; // Subtraction

console.log(val);

val = 7 % 5; // Modulus

console.log(val);

val = 7 ** 5; // Exponentiation

console.log(val);

val = 3;
val++; // Increment

console.log(val);

val--; // Decrement

console.log(val);

// Assignment Operators

let num = 10;

num += 2; // num = num + 2
num -= 5; // num = num - 5
num *= 2; // num = num * 2
num /= 2; // num = num / 2
num %= 5; // num = num % 5
console.log(num);

// Comparison Operators
console.log(6 == "6"); // Equality
console.log(7 != "7");
console.log(12 == "12");
console.log(12 === "12");

console.log(12 != "12");

console.log(12 !== "12");

console.log(5 > 2);
console.log(5 < 2);
console.log(5 >= 5);
console.log(5 <= 2);

// Logical Operators

console.log(!false);
console.log(5 > 2 && 7 > 2);
console.log(5 > 2 && 2 < 1);
console.log(5 > 1 || 2 < 1);
